namespace SqlFlow.Assistant;

/// <summary>
/// What a person is told about who writes the assistant's answers, written once so every surface (the GUI's chat, its
/// Explain, the Slack bot) says the same: that an AI language model writes them, which model and provider, and that an
/// answer can be wrong. A system that talks with people tells them they are talking with an AI system, and a system that
/// writes text marks that text as generated (the EU AI Act's Article 50); <see cref="Sentence"/> is the first, shown where a
/// conversation starts, and <see cref="Mark"/> the second, carried with each answer a person reads.
/// </summary>
public static class AssistantDisclosure
{
    /// <summary>The provider's name as a person reads it.</summary>
    public static string ProviderName(AssistantProvider provider) => provider switch
    {
        AssistantProvider.AzureFoundry => "Azure AI Foundry",
        AssistantProvider.OpenAI => "OpenAI",
        AssistantProvider.Anthropic => "Anthropic",
        _ => throw new ArgumentOutOfRangeException(nameof(provider), provider, "Not an assistant provider."),
    };

    /// <summary>The model and provider as one phrase, such as <c>gpt-5.1 on Azure AI Foundry</c>.</summary>
    public static string ModelLabel(AssistantProvider provider, string model)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(model);
        return $"{model.Trim()} on {ProviderName(provider)}";
    }

    /// <summary>The sentence a conversation starts under: who writes the answers and that they can be wrong.</summary>
    public static string Sentence(AssistantProvider provider, string model)
        => $"Answers are written by an AI language model ({ModelLabel(provider, model)}) and can be wrong: check what matters before you act on it.";

    /// <summary>The note one answer carries where it is read outside the chat that shows <see cref="Sentence"/>, such as a
    /// Slack thread.</summary>
    public static string Mark(AssistantProvider provider, string model)
        => $"AI-generated by {ModelLabel(provider, model)}; it can be wrong.";
}
