// What an answer says about the model that wrote it: the mark the chat shows under each answer, the metadata a thread
// message carries it in, and the header an exported answer is saved with, so a copy kept outside the chat still says it
// was generated, and by what, in a form a program can read.

/** The model that wrote an answer, as the API serves it (the control plane's ChatModelDto). */
export interface AnswerModel {
  /** The provider, by its configuration name (AzureFoundry, OpenAI, Anthropic). */
  provider: string;
  /** The model or deployment name. */
  model: string;
  /** Both as a person reads them, such as "gpt-5.1 on Azure AI Foundry". */
  label: string;
}

/** The key an answer's model rides under in a thread message's custom metadata. */
export const ANSWER_MODEL_KEY = "answerModel";

/** The custom metadata a thread message carries for the model that wrote it; none when the model is not recorded. */
export function answerMetadata(model: AnswerModel | null | undefined): Record<string, unknown> {
  return model ? { [ANSWER_MODEL_KEY]: model } : {};
}

/** The model a thread message's custom metadata carries, or null when it carries none (a stored answer from before
 * answers recorded their model, or one still streaming). */
export function answerModelOf(custom: Readonly<Record<string, unknown>> | undefined): AnswerModel | null {
  const value = custom?.[ANSWER_MODEL_KEY];
  if (typeof value !== "object" || value === null) {
    return null;
  }
  const { provider, model, label } = value as Record<string, unknown>;
  return typeof provider === "string" && typeof model === "string" && typeof label === "string"
    ? { provider, model, label }
    : null;
}

/** The mark under an answer: that it is AI-generated, and by which model when that is recorded. */
export function answerMarkText(model: AnswerModel | null): string {
  return model ? `AI-generated by ${model.label}` : "AI-generated";
}

/** A value fit for one line of the export's comment header: no line break, and no "--" that could close the comment. */
function headerValue(value: string): string {
  return value.replace(/[\r\n]+/g, " ").replace(/-{2,}/g, "-").trim();
}

/**
 * The Markdown an answer is exported as: a comment header a program reads (ai-generated, the provider and model, when
 * it was exported), the sentence a person reads, then the answer as the chat shows it.
 */
export function markedAnswerMarkdown(content: string, model: AnswerModel | null, exportedAt: Date): string {
  const header = ["<!--", "ai-generated: true"];
  if (model) {
    header.push(`provider: ${headerValue(model.provider)}`, `model: ${headerValue(model.model)}`);
  }
  header.push(`exported: ${exportedAt.toISOString()}`, "-->");
  return `${header.join("\n")}\n\n_${answerMarkText(model)}; it can be wrong._\n\n${content}`;
}
