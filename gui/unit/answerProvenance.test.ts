// What an answer says about the model that wrote it: the mark under it, the metadata it rides in, and the header an
// exported answer carries.

import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  ANSWER_MODEL_KEY, answerMarkText, answerMetadata, answerModelOf, markedAnswerMarkdown, type AnswerModel,
} from "../src/features/chat/answerProvenance.ts";

const foundry: AnswerModel = { provider: "AzureFoundry", model: "gpt-5.1", label: "gpt-5.1 on Azure AI Foundry" };

describe("answerMetadata and answerModelOf", () => {
  it("carry the model through a thread message's custom metadata", () => {
    assert.deepEqual(answerModelOf(answerMetadata(foundry)), foundry);
  });

  it("carry nothing for an answer whose model is not recorded", () => {
    assert.deepEqual(answerMetadata(null), {});
    assert.equal(answerModelOf(undefined), null);
    assert.equal(answerModelOf({}), null);
  });

  it("read no model from metadata of another shape", () => {
    assert.equal(answerModelOf({ [ANSWER_MODEL_KEY]: "gpt-5.1" }), null);
    assert.equal(answerModelOf({ [ANSWER_MODEL_KEY]: { provider: "OpenAI", model: "gpt-5-mini" } }), null);
  });
});

describe("answerMarkText", () => {
  it("names the model when the answer records it", () => {
    assert.equal(answerMarkText(foundry), "AI-generated by gpt-5.1 on Azure AI Foundry");
  });

  it("still says the answer is AI-generated when it does not", () => {
    assert.equal(answerMarkText(null), "AI-generated");
  });
});

describe("markedAnswerMarkdown", () => {
  const exported = new Date(Date.UTC(2026, 10, 5, 9, 30, 0));

  it("opens with a header a program reads, then the sentence a person reads, then the answer", () => {
    assert.equal(
      markedAnswerMarkdown("Three flows failed.", foundry, exported),
      [
        "<!--",
        "ai-generated: true",
        "provider: AzureFoundry",
        "model: gpt-5.1",
        "exported: 2026-11-05T09:30:00.000Z",
        "-->",
        "",
        "_AI-generated by gpt-5.1 on Azure AI Foundry; it can be wrong._",
        "",
        "Three flows failed.",
      ].join("\n"),
    );
  });

  it("marks an answer whose model is not recorded as generated all the same", () => {
    const marked = markedAnswerMarkdown("Nightly.", null, exported);
    assert.match(marked, /^<!--\nai-generated: true\nexported: /);
    assert.doesNotMatch(marked, /model:/);
    assert.match(marked, /_AI-generated; it can be wrong\._\n\nNightly\.$/);
  });

  it("keeps a model name from closing the comment or breaking its line", () => {
    const odd: AnswerModel = { provider: "OpenAI", model: "model-->\nx", label: "model on OpenAI" };
    const header = markedAnswerMarkdown("Text.", odd, exported).split("\n-->")[0];
    assert.match(header, /model: model-> x$/m);
    assert.doesNotMatch(header, /--[^>]*-->/);
  });
});
